#!/usr/bin/env node
// Writes each public page's SEO head (title, description, canonical, robots, Open Graph, Twitter and JSON-LD)
// from lib/acs-defaults.js into the static HTML, so crawlers and agents that do not run JavaScript see it too.
// acs-runtime.js still applies admin overrides on top in the browser.
//   node scripts/seo-head.js          update files
//   node scripts/seo-head.js --check  exit 1 if any page is out of date
const fs = require('node:fs');
const path = require('node:path');
const { PAGE_DEFAULTS } = require('../lib/acs-defaults');
const { mergeSeo } = require('../lib/admin-core');

const ROOT = path.resolve(__dirname, '..');
const START = '<!-- acs:seo:start (generated by scripts/seo-head.js from lib/acs-defaults.js) -->';
const END = '<!-- acs:seo:end -->';

const attr = (value) => String(value).replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const text = (value) => String(value).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

function headBlock(page) {
  const seo = mergeSeo(page.defaults, {});
  const json = JSON.stringify(JSON.parse(seo.jsonLd)).replace(/</g, '\\u003c');
  return [
    START,
    `<link rel="canonical" href="${attr(seo.canonical)}">`,
    `<meta name="robots" content="${attr(seo.robots)}">`,
    `<meta name="keywords" content="${attr(seo.keywords)}">`,
    `<meta property="og:type" content="${attr(seo.ogType)}">`,
    '<meta property="og:site_name" content="ACS Engitech">',
    '<meta property="og:locale" content="en_IN">',
    `<meta property="og:url" content="${attr(seo.canonical)}">`,
    `<meta property="og:title" content="${attr(seo.ogTitle)}">`,
    `<meta property="og:description" content="${attr(seo.ogDescription)}">`,
    `<meta property="og:image" content="${attr(seo.ogImage)}">`,
    '<meta property="og:image:width" content="1200">',
    '<meta property="og:image:height" content="630">',
    '<meta property="og:image:alt" content="ACS Engitech control panels and industrial automation">',
    `<meta name="twitter:card" content="${attr(seo.twitterCard)}">`,
    `<meta name="twitter:title" content="${attr(seo.twitterTitle)}">`,
    `<meta name="twitter:description" content="${attr(seo.twitterDescription)}">`,
    `<meta name="twitter:image" content="${attr(seo.twitterImage)}">`,
    '<link rel="alternate" type="text/markdown" href="/llms.txt" title="llms.txt">',
    `<script type="application/ld+json" data-acs-jsonld="true">${json}</script>`,
    END,
  ].join('\n');
}

function render(html, page) {
  const seo = mergeSeo(page.defaults, {});
  // Source pages may use CRLF while this generator writes LF. Remove every existing
  // generated block before adding the canonical one so a build remains idempotent.
  const start = START.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const end = END.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  let out = html.replace(new RegExp(`${start}[\\s\\S]*?${end}\\r?\\n`, 'g'), '');
  if (!/<title>[\s\S]*?<\/title>/.test(out)) throw new Error(`${page.file}: no <title>`);
  out = out.replace(/<title>[\s\S]*?<\/title>/, `<title>${text(seo.title)}</title>`);
  const description = `<meta name="description" content="${attr(seo.description)}">`;
  if (/<meta name="description" content="[^"]*">/.test(out)) out = out.replace(/<meta name="description" content="[^"]*">/, description);
  else out = out.replace(/<\/title>/, `</title>\n${description}`);
  return out.replace(/<\/head>/, `${headBlock(page)}\n</head>`);
}

function run({ check = false } = {}) {
  const stale = [];
  for (const page of PAGE_DEFAULTS) {
    const file = path.join(ROOT, page.file);
    const html = fs.readFileSync(file, 'utf8');
    const next = render(html, page);
    if (next === html) continue;
    stale.push(page.file);
    if (!check) fs.writeFileSync(file, next);
  }
  return stale;
}

if (require.main === module) {
  const check = process.argv.includes('--check');
  const stale = run({ check });
  if (check && stale.length) {
    console.error(`SEO head out of date in: ${stale.join(', ')}\nRun: node scripts/seo-head.js`);
    process.exit(1);
  }
  console.log(check ? 'SEO heads are up to date.' : `Updated ${stale.length} page(s).`);
}

module.exports = { headBlock, render, run, START, END };
