#!/usr/bin/env node
// Writes copy-ready SEO deliverables to docs/seo/: robots.txt, the llms.txt body for the admin, a preview
// of the full llms.txt, and the JSON-LD for every page. Source of truth: lib/acs-defaults.js.
const fs = require('node:fs');
const path = require('node:path');
const { PAGE_DEFAULTS, DEFAULT_SETTINGS } = require('../lib/acs-defaults');
const { buildLlmsTxt, buildSitemap, mergeSeo } = require('../lib/admin-core');

const OUT = path.resolve(__dirname, '..', 'docs', 'seo');
fs.mkdirSync(path.join(OUT, 'schema'), { recursive: true });
const pages = PAGE_DEFAULTS.map((page) => ({ ...page, seo: {} }));
const write = (file, body) => fs.writeFileSync(path.join(OUT, file), body.endsWith('\n') ? body : `${body}\n`);

write('robots.txt', DEFAULT_SETTINGS.robotsTxt);
write('llms-admin-body.md', DEFAULT_SETTINGS.llmsIntro);
write('llms.txt', buildLlmsTxt({ settings: DEFAULT_SETTINGS, pages, posts: [], positions: [] }));
write('sitemap-preview.xml', buildSitemap({ pages, posts: [] }));

const index = [];
for (const page of PAGE_DEFAULTS) {
  const slug = page.path === '/' ? 'home' : page.path.slice(1);
  write(`schema/${slug}.json`, JSON.stringify(JSON.parse(page.defaults.jsonLd), null, 2));
  index.push({ path: page.path, file: page.file, title: page.defaults.title, description: page.defaults.description, keywords: page.defaults.keywords, schema: `schema/${slug}.json` });
}
write('pages.json', JSON.stringify(index, null, 2));

// The nine checks shown in the admin SEO manager, evaluated for every page.
const CHECKS = [
  ['Title 30-60', (seo) => seo.title.length >= 30 && seo.title.length <= 60],
  ['Description 120-160', (seo) => seo.description.length >= 120 && seo.description.length <= 160],
  ['Focus keyword set', (seo) => Boolean(seo.focusKeyword)],
  ['Keyword in title', (seo) => Boolean(seo.focusKeyword) && seo.title.toLowerCase().includes(seo.focusKeyword.toLowerCase())],
  ['Keyword in description', (seo) => Boolean(seo.focusKeyword) && seo.description.toLowerCase().includes(seo.focusKeyword.toLowerCase())],
  ['Canonical absolute https', (seo) => /^https:\/\//.test(seo.canonical)],
  ['Indexable', (seo) => !/noindex/i.test(seo.robots)],
  ['Social image', (seo) => /^https?:\/\//.test(seo.ogImage)],
  ['JSON-LD present', (seo) => Boolean(seo.jsonLd)],
];
const csv = (value) => `"${String(value).replace(/"/g, '""')}"`;
const rows = [['SEO manager page', 'URL', 'File', 'Focus keyword', 'Title', 'Title length', 'Meta description', 'Description length', 'Keywords', ...CHECKS.map(([label]) => label), 'JSON-LD']];
const md = [
  '# SEO manager: every page',
  '',
  'Generated by `node scripts/export-seo-docs.js` from `lib/acs-defaults.js`. These are the defaults the admin SEO manager shows for each page and that are written into each page\'s HTML. All nine SEO manager checks are listed per page.',
  '',
  `Checks: ${CHECKS.map(([label]) => label).join(' · ')}`,
  '',
];
for (const page of PAGE_DEFAULTS) {
  const seo = mergeSeo(page.defaults, {});
  const results = CHECKS.map(([, test]) => test(seo));
  const slug = page.path === '/' ? 'home' : page.path.slice(1);
  rows.push([page.label, seo.canonical, page.file, seo.focusKeyword, seo.title, seo.title.length, seo.description, seo.description.length, seo.keywords, ...results.map((ok) => (ok ? 'Pass' : 'FAIL')), JSON.stringify(JSON.parse(seo.jsonLd))]);
  md.push(
    `## ${page.label}`,
    '',
    `- **URL:** ${seo.canonical}`,
    `- **File:** \`${page.file}\``,
    `- **Focus keyword:** ${seo.focusKeyword}`,
    `- **Title (${seo.title.length}):** ${seo.title}`,
    `- **Meta description (${seo.description.length}):** ${seo.description}`,
    `- **Keywords:** ${seo.keywords}`,
    `- **Robots:** ${seo.robots}`,
    `- **Social image:** ${seo.ogImage}`,
    `- **Checks:** ${results.every(Boolean) ? 'all 9 pass' : CHECKS.filter((_, i) => !results[i]).map(([label]) => `FAIL ${label}`).join(', ')}`,
    '',
    '<details><summary>JSON-LD</summary>',
    '',
    '```json',
    JSON.stringify(JSON.parse(seo.jsonLd), null, 2),
    '```',
    '',
    '</details>',
    '',
  );
}
write('seo-manager-pages.csv', rows.map((row) => row.map(csv).join(',')).join('\n'));
write('seo-manager-pages.md', md.join('\n'));
console.log(`Wrote ${index.length} page schemas and crawler files to ${path.relative(process.cwd(), OUT)}/`);
